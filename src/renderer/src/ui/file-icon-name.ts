/** 名字对应的图名(不带 .svg):文件名 > 多段扩展名 > 扩展名 > 通用文件;文件夹按名字,认不出用通用文件夹。 */
export function fileIconName(name: string, kind: "file" | "dir", open = false): string {
  const lower = name.toLowerCase();
  if (kind === "dir") {
    const icon = byFolder[lower] ?? "folder";
    return open ? `${icon}-open` : icon;
  }
  const named = byName[lower];
  if (named !== undefined) return named;
  const parts = lower.split(".");
  // 从最长的多段扩展名往短比(a.d.ts → "d.ts" → "ts");第一段是名字本身(".gitignore" 的第一段是空串)。
  for (let start = 1; start < parts.length; start++) {
    const icon = byExtension[parts.slice(start).join(".")];
    if (icon !== undefined) return icon;
  }
  return "file";
}
